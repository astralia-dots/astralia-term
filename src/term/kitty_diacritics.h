/* Binary search; returns the row/column/MSB value for a diacritic
 * codepoint, or -1 if cp isn't one of the 297 kitty diacritics. */
static inline int
kitty_diacritic_index(uint32_t cp) {
    int lo = 0, hi = KITTY_DIACRITIC_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (kitty_diacritics[mid].cp == cp)
            return kitty_diacritics[mid].idx;
        if (kitty_diacritics[mid].cp < cp)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return -1;
}
